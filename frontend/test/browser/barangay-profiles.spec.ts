import {test,expect} from '@playwright/test';
import {readFileSync,mkdirSync} from 'node:fs';
const names=JSON.parse(readFileSync('test/fixtures/barangay-profiles.json','utf8'));
for(const width of [375,768,1280,1920]) test(`compact Barangay Profiles at ${width}px`,async({page,context})=>{
  await page.setViewportSize({width,height:1000});
  await page.emulateMedia({reducedMotion:'reduce'});
  await context.route('**/*',route=>new URL(route.request().url()).hostname==='127.0.0.1'?route.continue():route.abort());
  await context.route('http://127.0.0.1:54321/**',route=>route.fulfill({json:[]}));
  await context.route('**/api/**',route=>route.fulfill({json:route.request().url().includes('/about/barangays')?names:[]}));
  await page.goto('/about/barangays');
  const main=page.locator('#main-content');
  const heading=main.getByRole('heading',{level:1,name:'Barangay profiles',exact:true});
  await expect(heading).toHaveCount(1);
  await expect(main.getByRole('status')).toHaveText(`${names.length} barangays`);
  const cards=main.getByRole('article');
  await expect(cards).toHaveCount(6);
  await expect(cards.locator('h2')).toHaveText(names.slice(0,6));
  await expect(main.locator('svg')).toHaveCount(0);
  const h=await heading.boundingBox(),header=await page.locator('header').first().boundingBox();
  expect(h!.y).toBeGreaterThan(header!.y+header!.height);
  const columns=await cards.first().evaluate(el=>getComputedStyle(el.parentElement!).gridTemplateColumns.split(' ').length);
  expect(columns).toBe(width>=1024?3:width>=640?2:1);
  const first=await cards.first().boundingBox();
  expect(first!.x).toBe(h!.x);
  const row=await cards.all();
  const heights=await Promise.all(row.slice(0,columns).map(async c=>(await c.boundingBox())!.height));
  expect(new Set(heights).size).toBe(1);
  const search=main.getByRole('searchbox');
  const s=await search.boundingBox();
  if(width>=768)expect(Math.abs(s!.x+s!.width-(await cards.locator('..').first().boundingBox())!.width-first!.x)).toBeLessThan(1);
  await expect(main.getByRole('button',{name:'Previous'})).toBeDisabled();
  await search.focus();await page.keyboard.press('Tab');
  await expect(main.getByRole('button',{name:'Page 1',exact:true})).toBeFocused();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await search.focus();
  mkdirSync('node_modules/.cache/barangay-profiles-review',{recursive:true});
  await page.screenshot({path:`node_modules/.cache/barangay-profiles-review/after-${width}.png`,fullPage:true});
  await main.getByRole('button',{name:'Page 5',exact:true}).click();
  await expect(cards).toHaveCount(1);
  await expect(cards.locator('h2')).toHaveText(names.slice(24));
  await expect(main.getByRole('button',{name:'Next'})).toBeDisabled();
  await search.fill('zzz');
  await expect(main.getByRole('status')).toHaveText('0 barangays');
  await expect(main.getByText('No barangays match your search')).toBeVisible();
  await search.fill('BAGACAY');
  await expect(cards.locator('h2')).toHaveText(['Bagacay']);
  await search.clear();
  await expect(main.getByRole('button',{name:'Page 1',exact:true})).toHaveAttribute('aria-current','page');
});
