import { test, expect } from '@playwright/test';
import { mkdirSync } from 'node:fs';
import { resolve } from 'node:path';
const artifacts = resolve('node_modules/.cache/barangay-cards');
test.beforeEach(async ({ context }) => {
  await context.route('**/*', route => new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort());
  await context.route('**/api/**', route => route.fulfill({ json: [] }));
});
for (const width of [320, 375, 768, 1280, 1920]) test(`barangay cards and location filters at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 1000 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto('/');
  await page.addStyleTag({ content: 'html{scroll-behavior:auto!important}' });
  const section = page.getByRole('region', { name: 'Barangays of Talibon' });
  await section.scrollIntoViewIfNeeded();
  const cards = section.getByRole('article');
  const filters = section.getByRole('group', { name: 'Browse by location' });
  await expect(cards).toHaveCount(6);
  await expect(section.getByRole('status')).toHaveText('Showing 1–6 of 25 barangays');
  const columns = await cards.first().evaluate(el => getComputedStyle(el.parentElement!).gridTemplateColumns.split(' ').length);
  expect(columns).toBe(width >= 1024 ? 3 : width >= 700 ? 2 : 1);
  const heights = await Promise.all((await cards.all()).slice(0, columns).map(async card => (await card.boundingBox())!.height));
  expect(new Set(heights).size).toBe(1);
  await filters.getByRole('radio', { name: 'All', exact: true }).focus();
  await page.keyboard.press('ArrowRight');
  await expect(filters.getByRole('radio', { name: 'Mainland', exact: true })).toBeChecked();
  await expect(section.getByRole('status')).toHaveText('Showing 1–6 of 17 barangays');
  await page.keyboard.press('ArrowRight');
  await expect(filters.getByRole('radio', { name: 'Island', exact: true })).toBeChecked();
  await expect(section.getByRole('status')).toHaveText('Showing 1–6 of 8 barangays');
  await section.getByRole('button', { name: 'Next' }).click();
  await expect(cards).toHaveCount(2);
  await expect(section.getByRole('button', { name: 'Next' })).toBeDisabled();
  await filters.getByRole('radio', { name: 'All', exact: true }).locator('..').click();
  await expect(cards).toHaveCount(6);
  await expect(section.getByRole('link', { name: 'View full directory' })).toHaveAttribute('href', '/about/barangays');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  mkdirSync(artifacts, { recursive: true });
  await section.screenshot({ path: resolve(artifacts, `after-${width}.png`), style: 'header,header *{visibility:hidden!important}' });
});
